use std::fs;
use std::path::PathBuf;

use levi_ui_gen::write::OutputTree;

const HEADER: &str = "// Generated by levi-ui-gen from design/tokens.json. Do not edit.\n";

fn tree(files: &[(&str, &str)]) -> OutputTree {
    let mut tree = OutputTree::default();
    for (path, body) in files {
        tree.insert(PathBuf::from(path), format!("{HEADER}{body}"));
    }
    tree
}

#[test]
fn write_then_diff_is_empty() {
    let dir = tempfile::tempdir().unwrap();
    let tree = tree(&[("mod.rs", "pub mod color;\n"), ("color/accent.rs", "pub struct Accent;\n")]);
    tree.write_to(dir.path()).unwrap();
    assert!(tree.diff(dir.path()).unwrap().is_empty());
    assert!(dir.path().join("color/accent.rs").is_file());
}

#[test]
fn diff_lists_changed_missing_and_stale_files() {
    let dir = tempfile::tempdir().unwrap();
    tree(&[("a.rs", "a\n"), ("b.rs", "b\n"), ("stale.rs", "s\n")]).write_to(dir.path()).unwrap();
    let next = tree(&[("a.rs", "a\n"), ("b.rs", "changed\n"), ("c.rs", "c\n")]);
    let diff = next.diff(dir.path()).unwrap();
    assert_eq!(diff, vec![PathBuf::from("b.rs"), PathBuf::from("c.rs"), PathBuf::from("stale.rs")]);
}

#[test]
fn write_removes_stale_generated_files_and_keeps_hand_written_ones() {
    let dir = tempfile::tempdir().unwrap();
    tree(&[("old/gone.rs", "g\n"), ("keep.rs", "k\n")]).write_to(dir.path()).unwrap();
    fs::write(dir.path().join("hand.rs"), "// written by hand\n").unwrap();
    tree(&[("keep.rs", "k\n")]).write_to(dir.path()).unwrap();
    assert!(!dir.path().join("old/gone.rs").exists());
    assert!(!dir.path().join("old").exists());
    assert!(dir.path().join("hand.rs").is_file());
}

#[test]
fn crlf_line_ends_are_not_a_difference() {
    let dir = tempfile::tempdir().unwrap();
    let tree = tree(&[("a.rs", "a\nb\n")]);
    tree.write_to(dir.path()).unwrap();
    let crlf = fs::read_to_string(dir.path().join("a.rs")).unwrap().replace('\n', "\r\n");
    fs::write(dir.path().join("a.rs"), crlf).unwrap();
    assert!(tree.diff(dir.path()).unwrap().is_empty());
}
