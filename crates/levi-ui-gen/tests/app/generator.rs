use std::fs;
use std::path::{Path, PathBuf};

use levi_ui_gen::app::{CliArgs, Generator};
use levi_ui_gen::error::GenError;
use levi_ui_gen::model::{OwnershipFile, TokenFile};

const THREE: &str = r##"{"tokens":[
  {"name":"--color-accent","type":"color","value":"#8B7CFF","description":"ACCENT"},
  {"name":"--color-focus-ring","type":"color","value":"var(--color-accent)"},
  {"name":"--spacing-row","type":"spacing","value":"28px"}
]}"##;

const THREE_OWNERS: &str =
    r#"{"owners":{"--color-accent":"levi-ui","--color-focus-ring":"levi-ui","--spacing-row":"levi-ui"}}"#;

fn tokens(json: &str) -> TokenFile {
    serde_json::from_str(json).unwrap_or_else(|error| panic!("token fixture: {error}"))
}

fn owners(json: &str) -> OwnershipFile {
    serde_json::from_str(json).unwrap_or_else(|error| panic!("ownership fixture: {error}"))
}

fn paths(tree: &levi_ui_gen::write::OutputTree) -> Vec<String> {
    tree.paths().map(|path| path.to_string_lossy().replace('\\', "/")).collect()
}

#[test]
fn writes_one_file_per_token() {
    let (levi, studio) = Generator::build(&tokens(THREE), &owners(THREE_OWNERS)).unwrap();
    assert_eq!(
        paths(&levi),
        vec!["color/accent.rs", "color/focus_ring.rs", "color/mod.rs", "mod.rs", "spacing/mod.rs", "spacing/row.rs"]
    );
    assert_eq!(paths(&studio), vec!["mod.rs"]);
    let accent = levi.get(Path::new("color/accent.rs")).unwrap();
    assert!(accent.starts_with("// Generated by levi-ui-gen from design/tokens.json. Do not edit.\n"));
    assert!(accent.contains("/// Paper: --color-accent. ACCENT\npub struct Accent;\n"));
    assert!(accent.contains("egui::Color32::from_rgba_unmultiplied_const(0x8B, 0x7C, 0xFF, 0xFF);"));
    let ring = levi.get(Path::new("color/focus_ring.rs")).unwrap();
    assert!(ring.contains("const VALUE: egui::Color32 = <super::accent::Accent as ColorToken>::VALUE;"));
    let row = levi.get(Path::new("spacing/row.rs")).unwrap();
    assert!(row.contains("const VALUE: f32 = 28.0;"));
}

#[test]
fn a_studio_token_aliases_a_general_token_across_crates() {
    let json = r##"{"tokens":[
      {"name":"--color-success","type":"color","value":"#4FD1A5"},
      {"name":"--color-status-works","type":"color","value":"var(--color-success)"}
    ]}"##;
    let own = r#"{"owners":{"--color-success":"levi-ui","--color-status-works":"studio-ui"}}"#;
    let (_, studio) = Generator::build(&tokens(json), &owners(own)).unwrap();
    let works = studio.get(Path::new("color/status_works.rs")).unwrap();
    assert!(works.contains("use levi_ui::tokens::ColorToken;"));
    assert!(works.contains("<levi_ui::tokens::generated::color::Success as ColorToken>::VALUE;"));
}

#[test]
fn adding_a_token_adds_one_file() {
    let dir = tempfile::tempdir().unwrap();
    let (before, _) = Generator::build(&tokens(THREE), &owners(THREE_OWNERS)).unwrap();
    before.write_to(dir.path()).unwrap();
    let four = THREE.replace(
        r#"{"name":"--spacing-row""#,
        r#"{"name":"--spacing-field","type":"spacing","value":"34px"},
  {"name":"--spacing-row""#,
    );
    let four_owners = THREE_OWNERS.replace(r#""--spacing-row""#, r#""--spacing-field":"levi-ui","--spacing-row""#);
    let (after, _) = Generator::build(&tokens(&four), &owners(&four_owners)).unwrap();
    assert_eq!(
        after.diff(dir.path()).unwrap(),
        vec![PathBuf::from("spacing/field.rs"), PathBuf::from("spacing/mod.rs")]
    );
}

#[test]
fn bad_value_names_token_and_writes_nothing() {
    let dir = tempfile::tempdir().unwrap();
    let tokens_path = dir.path().join("tokens.json");
    let owners_path = dir.path().join("ownership.json");
    let bad = THREE.replace("28px", "color-mix(in srgb, red, blue)");
    fs::write(&tokens_path, bad).unwrap();
    fs::write(&owners_path, THREE_OWNERS).unwrap();
    let (levi_out, studio_out) = (dir.path().join("levi"), dir.path().join("studio"));
    let args =
        CliArgs { tokens: tokens_path, ownership: owners_path, levi_out: levi_out.clone(), studio_out, check: false };
    match Generator::generate(&args) {
        Err(GenError::BadValue { token, .. }) => assert_eq!(token, "--spacing-row"),
        other => panic!("expected BadValue, got {other:?}"),
    }
    assert!(!levi_out.exists());
}

#[test]
fn check_writes_nothing_and_lists_changes() {
    let dir = tempfile::tempdir().unwrap();
    let tokens_path = dir.path().join("tokens.json");
    let owners_path = dir.path().join("ownership.json");
    fs::write(&tokens_path, THREE).unwrap();
    fs::write(&owners_path, THREE_OWNERS).unwrap();
    let (levi_out, studio_out) = (dir.path().join("levi"), dir.path().join("studio"));
    let mut args =
        CliArgs { tokens: tokens_path, ownership: owners_path, levi_out: levi_out.clone(), studio_out, check: true };
    assert_eq!(Generator::generate(&args).unwrap().len(), 7);
    assert!(!levi_out.exists());
    args.check = false;
    assert_eq!(Generator::generate(&args).unwrap().len(), 7);
    args.check = true;
    assert!(Generator::generate(&args).unwrap().is_empty());
}

#[test]
fn selector_enum_lists_variants_in_order() {
    let json = r##"{"tokens":[
      {"name":"--color-scene-1","type":"color","value":"#B5E853"},
      {"name":"--color-scene-2","type":"color","value":"#FF7AC6"}
    ]}"##;
    let own = r#"{"owners":{"--color-scene-1":"studio-ui","--color-scene-2":"studio-ui"},
      "selectors":[{"crate":"studio-ui","name":"SceneColor","variants":[["Pink","--color-scene-2"],["Lime","--color-scene-1"]]}]}"#;
    let (_, studio) = Generator::build(&tokens(json), &owners(own)).unwrap();
    let selector = studio.get(Path::new("selector/scene_color.rs")).unwrap();
    let pink = selector.find("    Pink,").unwrap();
    let lime = selector.find("    Lime,").unwrap();
    assert!(pink < lime);
    assert!(selector.contains("pub const ALL: [Self; 2] = [Self::Pink, Self::Lime];"));
    assert!(selector.contains("Self::Lime => <super::super::color::Scene1 as ColorToken>::VALUE,"));
    assert!(studio.get(Path::new("selector/mod.rs")).unwrap().contains("pub use scene_color::SceneColor;"));
    assert!(studio.get(Path::new("mod.rs")).unwrap().contains("pub mod selector;"));
}

#[test]
fn a_selector_cannot_name_a_missing_token() {
    let json = r##"{"tokens":[{"name":"--color-scene-1","type":"color","value":"#B5E853"}]}"##;
    let own = r#"{"owners":{"--color-scene-1":"studio-ui"},
      "selectors":[{"crate":"studio-ui","name":"SceneColor","variants":[["Lime","--color-scene-9"]]}]}"#;
    match Generator::build(&tokens(json), &owners(own)) {
        Err(GenError::BadSelector { selector, token }) => {
            assert_eq!(selector, "SceneColor");
            assert_eq!(token, "--color-scene-9");
        }
        other => panic!("expected BadSelector, got {other:?}"),
    }
}

#[test]
fn cli_args_parse() {
    let args = CliArgs::parse(
        ["--tokens", "t.json", "--ownership", "o.json", "--levi-out", "l", "--studio-out", "s", "--check"]
            .map(String::from),
    )
    .unwrap();
    assert_eq!(args.tokens, PathBuf::from("t.json"));
    assert_eq!(args.studio_out, PathBuf::from("s"));
    assert!(args.check);
    assert!(matches!(CliArgs::parse(["--tokens".to_owned()]), Err(GenError::Usage { .. })));
}
