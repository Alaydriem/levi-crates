use egui::Ui;

use super::GalleryState;
use super::sheet::{
    AvatarSheet, BannerSheet, CardFrameSheet, CheckboxSheet, ChipSheet, ColourFieldSheet, DragFieldSheet,
    DropdownSheet, EmptyStateSheet, IconButtonSheet, ListRowSheet, LoadingStateSheet, MenuItemSheet, ModalFrameSheet,
    NavEntrySheet, PageHeaderSheet, SectionCardSheet, SectionHeaderSheet, SegmentedSheet, SliderSheet,
    SplitterAndScrollSheet, StatusPillSheet, TabRowSheet, TableSheet, TextButtonSheet, TextFieldSheet, ToastSheet,
    ToggleSheet,
};

/// One gallery page per Paper widget sheet, in Paper order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum GallerySheet {
    Toggle,
    Slider,
    IconButton,
    TextButton,
    Chip,
    Dropdown,
    StatusPill,
    Checkbox,
    DragField,
    Segmented,
    MenuItem,
    TextField,
    TabRow,
    ColourField,
    CardFrame,
    ModalFrame,
    SectionHeader,
    EmptyState,
    LoadingState,
    PageHeader,
    ListRow,
    Avatar,
    NavEntry,
    Banner,
    SectionCard,
    Table,
    Toast,
    SplitterAndScroll,
}

impl GallerySheet {
    /// The width of every Paper widget artboard.
    pub const WIDTH: f32 = 1240.0;
    pub const ALL: [Self; 28] = [
        Self::Toggle,
        Self::Slider,
        Self::IconButton,
        Self::TextButton,
        Self::Chip,
        Self::Dropdown,
        Self::StatusPill,
        Self::Checkbox,
        Self::DragField,
        Self::Segmented,
        Self::MenuItem,
        Self::TextField,
        Self::TabRow,
        Self::ColourField,
        Self::CardFrame,
        Self::ModalFrame,
        Self::SectionHeader,
        Self::EmptyState,
        Self::LoadingState,
        Self::PageHeader,
        Self::ListRow,
        Self::Avatar,
        Self::NavEntry,
        Self::Banner,
        Self::SectionCard,
        Self::Table,
        Self::Toast,
        Self::SplitterAndScroll,
    ];

    /// The Paper sheet name, shown in the gallery's page list.
    pub fn name(self) -> &'static str {
        match self {
            Self::Toggle => "Toggle",
            Self::Slider => "Slider",
            Self::IconButton => "Icon button",
            Self::TextButton => "Text button",
            Self::Chip => "Chip + Chip style",
            Self::Dropdown => "Dropdown",
            Self::MenuItem => "Menu item",
            Self::StatusPill => "Status pill",
            Self::Checkbox => "Checkbox",
            Self::Segmented => "Segmented",
            Self::DragField => "Drag field",
            Self::TextField => "Text field",
            Self::TabRow => "Tab row",
            Self::ColourField => "Colour field",
            Self::CardFrame => "Card frame + surfaces",
            Self::ModalFrame => "Modal frame",
            Self::SectionHeader => "Section header",
            Self::EmptyState => "Empty state",
            Self::LoadingState => "Loading state",
            Self::PageHeader => "Page header",
            Self::ListRow => "List row",
            Self::Avatar => "Avatar",
            Self::NavEntry => "Nav entry",
            Self::Banner => "Banner",
            Self::SectionCard => "Section card",
            Self::Table => "Table header + Table row",
            Self::Toast => "Toast",
            Self::SplitterAndScroll => "Splitter + scroll",
        }
    }

    /// The snapshot file stem.
    pub fn file_name(self) -> &'static str {
        match self {
            Self::Toggle => "toggle",
            Self::Slider => "slider",
            Self::IconButton => "icon_button",
            Self::TextButton => "text_button",
            Self::Chip => "chip",
            Self::Dropdown => "dropdown",
            Self::MenuItem => "menu_item",
            Self::StatusPill => "status_pill",
            Self::Checkbox => "checkbox",
            Self::Segmented => "segmented",
            Self::DragField => "drag_field",
            Self::TextField => "text_field",
            Self::TabRow => "tab_row",
            Self::ColourField => "colour_field",
            Self::CardFrame => "card_frame",
            Self::ModalFrame => "modal_frame",
            Self::SectionHeader => "section_header",
            Self::EmptyState => "empty_state",
            Self::LoadingState => "loading_state",
            Self::PageHeader => "page_header",
            Self::ListRow => "list_row",
            Self::Avatar => "avatar",
            Self::NavEntry => "nav_entry",
            Self::Banner => "banner",
            Self::SectionCard => "section_card",
            Self::Table => "table",
            Self::Toast => "toast",
            Self::SplitterAndScroll => "splitter_and_scroll",
        }
    }

    pub fn show(self, ui: &mut Ui, state: &mut GalleryState) {
        match self {
            Self::Toggle => ToggleSheet::show(ui, state),
            Self::Slider => SliderSheet::show(ui, state),
            Self::IconButton => IconButtonSheet::show(ui, state),
            Self::TextButton => TextButtonSheet::show(ui, state),
            Self::Chip => ChipSheet::show(ui, state),
            Self::Dropdown => DropdownSheet::show(ui, state),
            Self::MenuItem => MenuItemSheet::show(ui, state),
            Self::StatusPill => StatusPillSheet::show(ui, state),
            Self::Checkbox => CheckboxSheet::show(ui, state),
            Self::Segmented => SegmentedSheet::show(ui, state),
            Self::DragField => DragFieldSheet::show(ui, state),
            Self::TextField => TextFieldSheet::show(ui, state),
            Self::TabRow => TabRowSheet::show(ui, state),
            Self::ColourField => ColourFieldSheet::show(ui, state),
            Self::CardFrame => CardFrameSheet::show(ui, state),
            Self::ModalFrame => ModalFrameSheet::show(ui, state),
            Self::SectionHeader => SectionHeaderSheet::show(ui, state),
            Self::EmptyState => EmptyStateSheet::show(ui, state),
            Self::LoadingState => LoadingStateSheet::show(ui, state),
            Self::PageHeader => PageHeaderSheet::show(ui, state),
            Self::ListRow => ListRowSheet::show(ui, state),
            Self::Avatar => AvatarSheet::show(ui, state),
            Self::NavEntry => NavEntrySheet::show(ui, state),
            Self::Banner => BannerSheet::show(ui, state),
            Self::SectionCard => SectionCardSheet::show(ui, state),
            Self::Table => TableSheet::show(ui, state),
            Self::Toast => ToastSheet::show(ui, state),
            Self::SplitterAndScroll => SplitterAndScrollSheet::show(ui, state),
        }
    }
}
